#!/usr/bin/env node
// ------------------------------------------------------------------------
// iSmartSchool – builds Index.html for the Apps Script web app from the
// SAME source files as the GitHub Pages site, so the two can never drift.
//
//   node make-gas-index.mjs [output-file]      (default: Index.html)
//
// Works from the flat upload layout (all files side by side) and from the
// folder layout (site/…, assets/js/…). No service worker, no install
// prompt, no CSP meta tag (Apps Script serves its own); the app talks to the
// server through google.script.run, which api.js already supports.
// ------------------------------------------------------------------------
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const roots = [here, join(here, '..'), join(here, '..', 'site'), join(process.cwd()), join(process.cwd(), 'site')];
const find = (names) => {
  for (const r of roots) for (const n of names) { const p = join(r, n); if (existsSync(p)) return p; }
  console.error('✖ Cannot find ' + names[0]); process.exit(1);
};
const read = (...names) => readFileSync(find(names), 'utf8');
const fail = (m) => { console.error('✖ ' + m); process.exit(1); };

const html = read('index.html', 'site/index.html');
const css = read('app.css', 'assets/css/app.css') + '\n' + read('offline.css', 'assets/css/offline.css');
const theme = read('theme-init.js', 'assets/js/theme-init.js');
const api = read('api.js', 'assets/js/api.js');
let app = read('app.js', 'assets/js/app.js');
const sync = read('sync-ui.js', 'assets/js/sync-ui.js');

// Excel tool: the Pages site serves its own copy; here it comes from a CDN.
const local = "var urls=['assets/vendor/exceljs.min.js'];";
if (!app.includes(local)) fail('app.js changed: the ExcelJS loader line was not found. Update make-gas-index.mjs.');
app = app.replace(local, "var urls=['https://cdnjs.cloudflare.com/ajax/libs/exceljs/4.4.0/exceljs.min.js','https://cdn.jsdelivr.net/npm/exceljs@4.4.0/dist/exceljs.min.js'];");

const body = (/<body[^>]*>([\s\S]*)<\/body>/i.exec(html) || fail('index.html has no <body>'))[1]
  .replace(/<script[^>]*src=[^>]*><\/script>\s*/gi, '');
const title = (/<title>([\s\S]*?)<\/title>/i.exec(html) || [0, 'iSmartSchool'])[1];
const safe = (js) => js.replace(/<\/script/gi, '<\\/script');   // never end the inline script early

// The Apps Script page has no API URL of its own: google.script.run is used.
const config = "window.ISS_CONFIG = { apiUrl: '', offlineCacheDays: 30, prefetchEveryMinutes: 10, maxSavedScreens: 300, cachePayroll: false };";

const out = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
  <meta name="theme-color" content="#152230">
  <meta name="color-scheme" content="dark light">
  <title>${title}</title>
  <!-- GENERATED by make-gas-index.mjs from the GitHub Pages sources. Do not edit by hand. -->
  <script>${safe(theme)}</script>
  <style>
${css.replace(/<\/style/gi, '<\\/style')}
  </style>
</head>
<body>
${body}
<script>${config}</script>
<script>
${safe(api)}
</script>
<script>
${safe(app)}
</script>
<script>
${safe(sync)}
</script>
</body>
</html>
`;
const target = resolve(process.argv[2] || 'Index.html');
writeFileSync(target, out);
console.log('✔ ' + target + ' (' + Math.round(out.length / 1024) + ' KB) from the shared sources');
